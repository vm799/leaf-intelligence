// Utility functions for searching and filtering the data
const searchFunctions = {
  // Search by device name (case insensitive)
  searchByDeviceName: function(query) {
    return fdaDeNovoDevices.filter(device => 
      device.deviceName.toLowerCase().includes(query.toLowerCase())
    );
  },

  // Search by requester/company name (case insensitive)
  searchByRequester: function(query) {
    return fdaDeNovoDevices.filter(device => 
      device.requester.toLowerCase().includes(query.toLowerCase())
    );
  },

  // Search by De Novo number
  searchByDeNovoNumber: function(query) {
    return fdaDeNovoDevices.filter(device => 
      device.deNovoNumber.toLowerCase().includes(query.toLowerCase())
    );
  },

  // Search by 510(k) number
  searchByFiveOneOkNumber: function(query) {
    return fdaDeNovoDevices.filter(device => 
      device.fiveOneOkNumber.toLowerCase().includes(query.toLowerCase())
    );
  },

  // Filter by date range
  filterByDateRange: function(startDate, endDate) {
    return fdaDeNovoDevices.filter(device => {
      const deviceDate = new Date(device.decisionDate);
      const start = new Date(startDate);
      const end = new Date(endDate);
      return deviceDate >= start && deviceDate <= end;
    });
  },

  // Filter by year
  filterByYear: function(year) {
    return fdaDeNovoDevices.filter(device => 
      device.decisionDate.includes(year.toString())
    );
  },

  // General search across all fields
  globalSearch: function(query) {
    const lowerQuery = query.toLowerCase();
    return fdaDeNovoDevices.filter(device => 
      device.deviceName.toLowerCase().includes(lowerQuery) ||
      device.requester.toLowerCase().includes(lowerQuery) ||
      device.deNovoNumber.toLowerCase().includes(lowerQuery) ||
      device.fiveOneOkNumber.toLowerCase().includes(lowerQuery) ||
      device.decisionDate.includes(lowerQuery)
    );
  },

  // Get devices approved in the last N days
  getRecentDevices: function(days = 30) {
    const cutoffDate = new Date();
    cutoffDate.setDate(cutoffDate.getDate() - days);
    
    return fdaDeNovoDevices.filter(device => {
      const deviceDate = new Date(device.decisionDate);
      return deviceDate >= cutoffDate;
    });
  },

  // Sort devices by date (newest first by default)
  sortByDate: function(ascending = false) {
    return [...fdaDeNovoDevices].sort((a, b) => {
      const dateA = new Date(a.decisionDate);
      const dateB = new Date(b.decisionDate);
      return ascending ? dateA - dateB : dateB - dateA;
    });
  },

  // Get unique requesters
  getUniqueRequesters: function() {
    return [...new Set(fdaDeNovoDevices.map(device => device.requester))].sort();
  },

  // Get devices by specific requester
  getDevicesByRequester: function(requesterName) {
    return fdaDeNovoDevices.filter(device => 
      device.requester.toLowerCase() === requesterName.toLowerCase()
    );
  },

  // Get summary statistics
  getSummaryStats: function() {
    return {
      totalDevices: fdaDeNovoDevices.length,
      dateRange: {
        earliest: fdaDeNovoDevices.reduce((min, device) => 
          new Date(device.decisionDate) < new Date(min.decisionDate) ? device : min
        ).decisionDate,
        latest: fdaDeNovoDevices.reduce((max, device) => 
          new Date(device.decisionDate) > new Date(max.decisionDate) ? device : max
        ).decisionDate
      },
      uniqueRequesters: new Set(fdaDeNovoDevices.map(device => device.requester)).size,
      devicesWithFiveOneOk: fdaDeNovoDevices.filter(device => device.fiveOneOkNumber !== "").length
    };
  }
};

